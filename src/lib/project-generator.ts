// ============================================================
// Утилиты
// ============================================================

function pick<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

// ============================================================
// Публичный API
// ============================================================

export interface RandomProjectIdea {
  name: string;
  description: string;
  genre: string;
}

/**
 * Сгенерировать случайную, но связную концепцию проекта.
 * Название = прилагательное + существительное (звучит как название игры).
 * Описание = протагонист в сеттинге + хук + механика.
 * Жанр = случайный из таксономии.
 */
export function generateRandomProject(): RandomProjectIdea {
  const name = `${pick(ADJECTIVES)} ${pick(NOUNS)}`;
  const description = `Игрок — ${pick(PROTAGONISTS)} в ${pick(
    SETTINGS
  )}, который ${pick(HOOKS)}. Ключевая механика — ${pick(MECHANICS)}.`;
  const genre = pick(GENRES).label;

  return { name, description, genre };
}
